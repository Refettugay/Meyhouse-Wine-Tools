// Bar Recipe Book seed -> SQL. Prints one SQL statement for
// beverage.bar_recipe + bar_recipe_ingredient from prisma/seed-data/bar_recipes_seed.json.
//
//   node scripts/bar-recipes-seed-sql.mjs > seed.sql
//   node scripts/bar-recipes-seed-sql.mjs --chunk 2/4   (2nd quarter of the recipes, for size-limited SQL runners)
//
// Idempotent and non-destructive: a recipe whose id already exists is left alone
// (ON CONFLICT DO NOTHING), and ingredients are only inserted for recipes created
// by THIS run — so re-running never overwrites edits made in the app.
//
// Mapping (spec section 3): scale_mode from the seed if given (Limonata/Ayran =
// liters, syrups = multiplier); otherwise craft/na -> portions if batchable else
// none; classics -> none. build keys -> glass/ice/garnish/how_to. Unit "gr" -> "g".

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const file = fileURLToPath(new URL("../prisma/seed-data/bar_recipes_seed.json", import.meta.url));
const all = JSON.parse(readFileSync(file, "utf8"));
const chunkArg = process.argv[process.argv.indexOf("--chunk") + 1];
let recipes = all;
if (process.argv.includes("--chunk")) {
  const [k, n] = chunkArg.split("/").map(Number);
  const size = Math.ceil(all.length / n);
  recipes = all.slice((k - 1) * size, k * size);
}

const lit = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === null || v === undefined || v === "" ? "null" : String(Number(v)));
const bool = (v) => (v ? "true" : "false");
const json = (v) => (v === null || v === undefined ? "null" : `${lit(JSON.stringify(v))}::jsonb`);

// {en, tr, es} from an English value + an i18n map; drops empty languages.
function tri(en, i18n) {
  if (en === null || en === undefined || en === "") return null;
  const out = { en };
  for (const k of ["tr", "es"]) if (i18n && i18n[k]) out[k] = i18n[k];
  return out;
}
const joinLines = (v) => (Array.isArray(v) ? v.join("\n") : v);

function scaleMode(r) {
  if (r.scale_mode) return r.scale_mode;
  if (r.category === "craft" || r.category === "na") return r.batchable ? "portions" : "none";
  return "none";
}
function storage(s) {
  if (!s) return null;
  if (/freezer/i.test(s)) return "freezer";
  if (/fridge/i.test(s)) return "fridge";
  throw new Error(`unknown storage: ${s}`);
}
const UNITS = new Set(["oz", "dash", "kg", "g", "L", "ea", "cup", "ml"]);
function unit(u) {
  if (u === null || u === undefined) return null;
  if (u === "gr") return "g";
  if (!UNITS.has(u)) throw new Error(`unknown unit: ${u}`);
  return u;
}

const recipeRows = [];
const ingRows = [];
recipes.forEach((r) => {
  const idx = all.indexOf(r);
  const b = r.build || {};
  const i = r.i18n || {};
  const notesI18n = i.notes ? { tr: joinLines(i.notes.tr), es: joinLines(i.notes.es) } : null;
  const subtitle = r.subtitle ? { en: r.subtitle } : null;
  recipeRows.push(
    "(" +
      [
        lit(r.id),
        lit(r.name),
        json(subtitle),
        lit(r.category),
        `array[${r.stores.map(lit).join(",")}]::text[]`,
        lit(scaleMode(r)),
        bool(r.batchable),
        num(r.default_portions),
        num(r.dilution_pct ?? 0),
        num(r.pour_from_batch_oz),
        json(tri(b.Glass, i.glass)),
        json(tri(b.Ice, i.ice)),
        json(tri(b.Garnish, i.garnish)),
        json(tri(b["How to"], i.how_to)),
        lit(storage(r.storage)),
        json(tri(joinLines(r.notes), notesI18n)),
        json(r.method ?? null),
        num(r.base_yield_l),
        num(r.glass_l),
        bool(r.needs_review),
        bool(r.needs_spec),
        String((idx + 1) * 10),
      ].join(", ") +
      ")",
  );
  r.ingredients.forEach((g, j) => {
    ingRows.push(
      "(" +
        [
          lit(r.id),
          String((j + 1) * 10),
          json(tri(g.name, g.name_i18n)),
          lit(g.batch_name),
          num(g.qty),
          lit(unit(g.unit)),
          json(tri(g.text, g.text_i18n)),
          bool(g.in_batch ?? true),
          json(tri(g.note, g.note_i18n)),
        ].join(", ") +
        ")",
    );
  });
});

process.stdout.write(`-- Generated by scripts/bar-recipes-seed-sql.mjs from ${recipes.length} recipes / ${ingRows.length} ingredients.
with new_recipes as (
  insert into beverage.bar_recipe
    (id, name, subtitle, category, stores, scale_mode, batchable, default_portions, dilution_pct,
     pour_from_batch_oz, glass, ice, garnish, how_to, storage, notes, method, base_yield_l, glass_l,
     needs_review, needs_spec, sort_order)
  values
  ${recipeRows.join(",\n  ")}
  on conflict (id) do nothing
  returning id
)
insert into beverage.bar_recipe_ingredient (recipe_id, sort_order, name, batch_name, qty, unit, text, in_batch, note)
select v.recipe_id, v.sort_order, v.name, v.batch_name::text, v.qty::numeric, v.unit::text, v.text::jsonb, v.in_batch, v.note::jsonb
from (values
  ${ingRows.join(",\n  ")}
) as v(recipe_id, sort_order, name, batch_name, qty, unit, text, in_batch, note)
join new_recipes n on n.id = v.recipe_id;
`);
