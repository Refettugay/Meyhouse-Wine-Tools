const DICTS: Record<Lang, Dict> = { en, tr, es };

export function makeT(lang: Lang) {
  return (key: string, ...args: string[]): string => {
    const v = DICTS[lang][key] ?? en[key] ?? key;
    return typeof v === "function" ? v(...args) : v;
  };
}

// Recipe content in the chosen language; falls back to English.
export function pick(v: Tri | null | undefined, lang: Lang): string {
  if (!v) return "";
  return v[lang] || v.en || "";
}

